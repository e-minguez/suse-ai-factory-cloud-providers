#!/usr/bin/env bash
# Writes requirements.txt: oci-cli and every dependency pinned to the wheels for
# CPython 3.13 (python313 in the image) on x86_64 and aarch64, with their sha256.
# The Dockerfile installs it with pip --require-hashes.
#
#   tools/webui/oci-cli/lock.sh <oci-cli version>      needs pip3 and network
set -euo pipefail

[ $# -eq 1 ] || { echo "usage: $0 <oci-cli version>" >&2; exit 2; }
version=$1
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

sha256() { if command -v sha256sum >/dev/null; then sha256sum "$1"; else shasum -a 256 "$1"; fi | cut -d' ' -f1; }

for arch in x86_64 aarch64; do
  plats=()
  for t in manylinux_2_34 manylinux_2_28 manylinux_2_17 manylinux2014; do plats+=(--platform "${t}_${arch}"); done
  pip3 download --quiet --disable-pip-version-check --no-cache-dir --only-binary=:all: \
    --implementation cp --python-version 3.13 --abi cp313 --abi abi3 --abi none "${plats[@]}" \
    -d "$work/$arch" "oci-cli==$version"
done

# One line per package: name==version and the hash of each arch's wheel.
for f in "$work"/*/*.whl; do
  base=$(basename "$f")
  name=$(cut -d- -f1 <<<"$base" | tr '[:upper:]_.' '[:lower:]--')
  ver=$(cut -d- -f2 <<<"$base")
  printf '%s==%s %s\n' "$name" "$ver" "$(sha256 "$f")"
done | sort -u | awk '
  $1 != prev { if (prev != "") print line; line = $1; prev = $1 }
  { line = line " \\\n    --hash=sha256:" $2 }
  END { print line }' >"$work/body"

if [ "$(cut -d= -f1 "$work/body" | grep -v '^ ' | sort | uniq -d)" ]; then
  echo "error: the arches resolved different versions" >&2
  exit 1
fi
{
  echo "# Generated by tools/webui/oci-cli/lock.sh $version. Do not edit."
  cat "$work/body"
} >"$here/requirements.txt"
echo "wrote $here/requirements.txt ($(grep -c '==' "$here/requirements.txt") packages)"
